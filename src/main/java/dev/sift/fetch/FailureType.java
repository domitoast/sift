package dev.sift.fetch;

/**
 * 抓取失敗的分類。
 *
 * <p>分這兩類的目的只有一個：<b>判斷「下次還要不要再試」。</b>
 *
 * <p>與資料庫的 {@code ck_fetch_job_failure_type} 約束一致。
 */
public enum FailureType {

    /**
     * 暫時性失敗——下次排程可望成功。
     *
     * <p>例如：timeout、連線被拒、對方回 500、對方回 503 維護中。
     *
     * <p>這類失敗<b>不是來源的錯</b>，不需要通知使用者。
     */
    TRANSIENT,

    /**
     * 永久性失敗——不處理的話下次還是會失敗。
     *
     * <p>例如：404 網址不存在、回應不是合法的 XML、對方回 403 拒絕存取。
     *
     * <p>這類失敗<b>需要人去看</b>——可能網站改版了，或使用者填錯網址。
     */
    PERMANENT
}
